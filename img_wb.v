`timescale 1ns / 1ps

//==============================================================================
// img_wb.v  --  RGB 白平衡校正（纯组合逻辑）
//
//   实测：画面白色偏红，三通道约为 R:B:G = 1 : 0.78 : 0.49
//   因此把 G 放大 2 倍、B 放大 1.25 倍，R 不变，使白色回到中性
//
//   常数调整方法：
//     G 增益 = 2x    —— 改 {1'b0,g} + {1'b0,g} 的倍率
//     B 增益 = 1.25x —— 改 b + (b>>2)
//   任何一档都受此校正影响（校正加在所有图像处理之前）
//==============================================================================

module img_wb (
    input  wire [15:0] din,
    output wire [15:0] dout
);

    wire [4:0] r = din[15:11];
    wire [5:0] g = din[10:5];
    wire [4:0] b = din[4:0];

    // 默认直通（增益 1:1:1）。
    // 若确认偏色方向固定，再改下面三行的倍率：
    //   G 增益：{1'b0,g} + {1'b0,g}        = 2.0x
    //   B 增益：{1'b0,b} + {3'b000,b[4:2]} = 1.25x
    //   R 增益：{1'b0,r} + {3'b000,r[4:3]} = 1.15x
    wire [5:0] g_o = g;
    wire [4:0] b_o = b;
    wire [4:0] r_o = r;

    assign dout = {r_o, g_o, b_o};

endmodule
